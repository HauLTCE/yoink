"""Generates flat self-contained single-file output across Python and 14 non-Python languages."""

from __future__ import annotations

import ast
import re
from pathlib import Path

from yoink.closure import _resolve_python_import
from yoink.lang import LangSpec
from yoink.model import Closure, EmitResult, ImportEdge, ModuleGraph
from yoink.slice import needed_defns, parse_module, stmt_defined_names, topo_order
from yoink.util import ensure_safe_write_path, read_text


def _used_names_in_stmts(stmts: list[ast.stmt]) -> set[str]:
    used: set[str] = set()
    for s in stmts:
        for sub in ast.walk(s):
            if isinstance(sub, ast.Name) and isinstance(sub.ctx, ast.Load):
                used.add(sub.id)
    return used


def _flat_python(
    graph: ModuleGraph,
    closure: Closure,
    ordered_mods: list[str],
    target_symbol: str | None,
    target_module: str | None,
) -> tuple[str, list[str]]:
    """Slice Python AST definitions in topological order and deduplicate external/stdlib imports."""
    warnings: list[str] = []
    future_imports: list[str] = []
    header_imports: list[str] = []
    seen_imports: set[str] = set()
    body_chunks: list[str] = []

    for mod_name in ordered_mods:
        info = graph.modules.get(mod_name)
        if info is None:
            continue
        lines = read_text(info.path).splitlines()
        tree = parse_module(info)
        keep_names = needed_defns(
            graph,
            closure,
            mod_name,
            target_symbol=target_symbol,
            target_module=target_module,
        )

        # First pass: collect kept body AST statements in this module so we know which imports are actually used
        kept_body_stmts: list[tuple[int, int, ast.stmt]] = []
        for stmt in tree.body:
            if isinstance(stmt, (ast.Import, ast.ImportFrom)):
                continue
            stmt_names = stmt_defined_names(stmt)
            if stmt_names & keep_names:
                if isinstance(stmt, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)):
                    start_line = min([stmt.lineno, *(d.lineno for d in stmt.decorator_list)])
                else:
                    start_line = stmt.lineno
                end_line = stmt.end_lineno or stmt.lineno
                kept_body_stmts.append((start_line, end_line, stmt))

        used_in_kept = _used_names_in_stmts([s for _, _, s in kept_body_stmts]) | keep_names

        mod_body: list[str] = []
        # Second pass: process imports (filtering out unused external imports from sliced-out functions)
        for stmt in tree.body:
            if not isinstance(stmt, (ast.Import, ast.ImportFrom)):
                continue
            if isinstance(stmt, ast.ImportFrom) and stmt.module == "__future__":
                src_seg = "\n".join(lines[stmt.lineno - 1 : (stmt.end_lineno or stmt.lineno)]).strip()
                if src_seg and src_seg not in seen_imports:
                    seen_imports.add(src_seg)
                    future_imports.append(src_seg)
                continue

            edge = ImportEdge(
                importer=mod_name,
                module=stmt.module or "" if isinstance(stmt, ast.ImportFrom) else stmt.names[0].name,
                names=tuple((a.name, a.asname) for a in stmt.names),
                level=getattr(stmt, "level", 0) or 0,
            )
            internal_hits = [
                h for h in _resolve_python_import(edge, graph.modules) if h in closure.modules
            ]
            if internal_hits:
                for a in stmt.names:
                    if a.asname and a.asname != a.name and "." not in a.name:
                        if a.asname in used_in_kept:
                            alias_line = f"{a.asname} = {a.name}"
                            if alias_line not in mod_body:
                                mod_body.append(alias_line)
                continue

            # Only emit stdlib/external import if at least one of its bound names is used in kept_body_stmts
            bound_import_names = {
                (a.asname or a.name).split(".")[0] for a in stmt.names if a.name != "*"
            }
            if bound_import_names and not (bound_import_names & used_in_kept):
                continue

            src_seg = "\n".join(lines[stmt.lineno - 1 : (stmt.end_lineno or stmt.lineno)]).strip()
            if src_seg and src_seg not in seen_imports:
                seen_imports.add(src_seg)
                header_imports.append(src_seg)

        for start_line, end_line, _ in kept_body_stmts:
            chunk = "\n".join(lines[start_line - 1 : end_line])
            mod_body.append(chunk)

        if mod_body:
            body_chunks.append(f"# --- module: {mod_name} ---\n" + "\n\n".join(mod_body))

    sections: list[str] = ["# Generated by yoink (flat mode)"]
    if future_imports:
        sections.append("\n".join(future_imports))
    if header_imports:
        sections.append("\n".join(header_imports))
    sections.extend(body_chunks)
    return "\n\n".join(sections) + "\n", warnings


def _comment_prefix(lang_id: str) -> str:
    if lang_id in ("ruby", "elixir", "python"):
        return "#"
    if lang_id == "lua":
        return "--"
    return "//"


def _flat_generic(
    graph: ModuleGraph,
    closure: Closure,
    ordered_mods: list[str],
    spec: LangSpec | None,
    target_symbol: str | None,
    target_module: str | None,
) -> tuple[str, list[str]]:
    """Order non-Python modules topologically and strip internal duplicate headers."""
    warnings: list[str] = []
    pfx = _comment_prefix(graph.language)
    chunks: list[str] = [f"{pfx} Generated by yoink (flat mode)"]

    inlined_filenames = {
        graph.modules[m].path.name for m in ordered_mods if m in graph.modules
    }

    for mod_name in ordered_mods:
        info = graph.modules.get(mod_name)
        if info is None:
            continue
        raw = read_text(info.path)
        filtered_lines: list[str] = []
        for line in raw.splitlines():
            s = line.strip()
            if graph.language == "cpp":
                if s == "#pragma once":
                    continue
                m_inc = re.match(r'^#\s*include\s*"([^"]+)"', s)
                if m_inc and Path(m_inc.group(1)).name in inlined_filenames:
                    continue
            filtered_lines.append(line)
        body = "\n".join(filtered_lines).strip()
        if body:
            chunks.append(f"{pfx} --- module: {mod_name} ({info.path.name}) ---\n{body}")

    return "\n\n".join(chunks) + "\n", warnings


def emit_flat(
    graph: ModuleGraph,
    closure: Closure,
    source_root: Path,
    out_path: Path,
    spec: LangSpec | None = None,
    target_symbol: str | None = None,
    target_module: str | None = None,
) -> EmitResult:
    """Generate a single flat self-contained source file at `out_path`."""
    out_path = Path(out_path).resolve()
    ensure_safe_write_path(out_path, out_path.parent)
    out_path.parent.mkdir(parents=True, exist_ok=True)

    ordered = topo_order(graph, closure.modules, root_mod=target_module)
    if graph.language == "python":
        content, warnings = _flat_python(graph, closure, ordered, target_symbol, target_module)
    else:
        content, warnings = _flat_generic(
            graph, closure, ordered, spec, target_symbol, target_module
        )

    out_path.write_text(content, encoding="utf-8")
    return EmitResult(files=[out_path], warnings=warnings, output_dir=out_path.parent)
